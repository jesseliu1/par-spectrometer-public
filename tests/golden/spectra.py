"""Deterministic synthetic golden spectra (R-3-2): generator and loader.

Each spectrum is what the MCU delivers: 701 unsigned 16-bit integers for 350–1050 nm (1 nm step) plus the
spectral coefficient, so that E(λ) = raw / 10**coefficient W·m⁻²·nm⁻¹ — the exact input of
par_app.math_ops.software_metrics(raw_points, coefficient).

The data lives in spectra.json (data and generator are kept apart, R-3-2). Regenerate with
    python -m tests.golden.spectra
and a unit test checks that the stored data still equals the generator output.
"""

from __future__ import annotations

import json
import math
from dataclasses import dataclass
from pathlib import Path

DATA = Path(__file__).with_name("spectra.json")
WAVELENGTHS = range(350, 1051)
UINT16_MAX = 65535
BOLTZMANN = 1.380649e-23  # J/K, exact (SI 2019)
PLANCK = 6.62607015e-34
LIGHT_SPEED = 299_792_458.0


@dataclass(frozen=True)
class Spectrum:
    name: str
    description: str
    coefficient: int
    raw_points: list[int]


def _planck(nm: int, kelvin: float) -> float:
    lam = nm * 1e-9
    return 1.0 / (lam**5 * math.expm1(PLANCK * LIGHT_SPEED / (lam * BOLTZMANN * kelvin)))


def _scaled(values: list[float], peak_counts: int) -> list[int]:
    top = max(values)
    return [int(round(v / top * peak_counts)) for v in values]


def _gaussian(nm: int, centre: float, fwhm: float) -> float:
    sigma = fwhm / (2 * math.sqrt(2 * math.log(2)))
    return math.exp(-0.5 * ((nm - centre) / sigma) ** 2)


def generate() -> list[Spectrum]:
    mono = [0] * len(WAVELENGTHS)
    mono[550 - 350] = 10000
    led = [
        40000 * _gaussian(nm, 450, 20) + 60000 * _gaussian(nm, 660, 20) + 20000 * _gaussian(nm, 730, 25)
        for nm in WAVELENGTHS
    ]
    return [
        Spectrum("flat", "flat 1 W/m²/nm (raw 1000, coefficient 3)", 3, [1000] * len(WAVELENGTHS)),
        Spectrum("mono_550", "single line 100 W/m²/nm at 550 nm (raw 10000, coefficient 2)", 2, mono),
        Spectrum(
            "blackbody_2856K",
            "Planck 2856 K (CIE illuminant A), peak scaled to 60000 counts, coefficient 4",
            4,
            _scaled([_planck(nm, 2856.0) for nm in WAVELENGTHS], 60000),
        ),
        Spectrum(
            "blackbody_5778K",
            "Planck 5778 K (solar photosphere, daylight stand-in), peak scaled to 60000 counts, coefficient 4",
            4,
            _scaled([_planck(nm, 5778.0) for nm in WAVELENGTHS], 60000),
        ),
        Spectrum(
            "led_450_660_730",
            "three Gaussian LED lines 450 nm (40000, FWHM 20), 660 nm (60000, FWHM 20), 730 nm (20000, FWHM 25), "
            "coefficient 3",
            3,
            [int(round(v)) for v in led],
        ),
    ]


def load() -> list[Spectrum]:
    payload = json.loads(DATA.read_text(encoding="utf-8"))
    return [Spectrum(**item) for item in payload["spectra"]]


def main() -> None:
    spectra = generate()
    for spectrum in spectra:
        assert len(spectrum.raw_points) == len(WAVELENGTHS)
        assert all(0 <= v <= UINT16_MAX for v in spectrum.raw_points)
    note = "Generated by tests/golden/spectra.py. Inputs only; expected values come from reference.py."
    rows = ",\n  ".join(
        json.dumps(spectrum.__dict__, ensure_ascii=False, separators=(",", ":")) for spectrum in spectra
    )
    DATA.write_text(f'{{"note": {json.dumps(note)},\n "spectra": [\n  {rows}\n ]}}\n', encoding="utf-8")


if __name__ == "__main__":
    main()
