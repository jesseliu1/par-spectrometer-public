"""Status-quo snapshots for metrics whose definition is pending a decision (R-3-2).

These values are produced BY THE CODE UNDER TEST and are therefore NOT golden reference values. They exist only
so that any change to a pending metric is visible in review and needs a deliberate snapshot update:
  * chlorophyll_a_ypfd / chlorophyll_b_ypfd — weight curve source pending D-102 (9-anchor Catmull-Rom curve in
    par_app/math_ops.py vs the 300-point table in docs/algorithms/chlorophyll_weights.py).
The former dli_d126 snapshot (legacy record with dli_eligible = NULL) was removed when D-126 was decided
(owner 2026-10-17); the decided rule is a correctness test now (tests/qt/test_golden_dli.py,
tests/unit/test_dli_legacy_review.py).

Kept in status_quo.json, apart from the independent reference (reference.py). Regenerate with
    python -m tests.golden.status_quo
only together with the D-102 decision or another change approved by owner (R-3-2: metric definitions).
"""

from __future__ import annotations

import json
from pathlib import Path

from tests.golden import spectra

DATA = Path(__file__).with_name("status_quo.json")
PENDING_METRICS = ("chlorophyll_a_ypfd", "chlorophyll_b_ypfd")


def load() -> dict[str, dict[str, float]]:
    return dict(json.loads(DATA.read_text(encoding="utf-8"))["values"])


def main() -> None:
    from par_app.math_ops import software_metrics

    values = {}
    for spectrum in spectra.load():
        metrics = software_metrics(spectrum.raw_points, spectrum.coefficient)
        values[spectrum.name] = {name: float(f"{metrics[name]:.12g}") for name in PENDING_METRICS}
    payload = {
        "note": (
            "STATUS QUO of V1.0.2, not correct values. Pending D-102 (values). Generated by tests/golden/status_quo.py."
        ),
        "unit": "µmol·m⁻²·s⁻¹",
        "values": values,
    }
    DATA.write_text(json.dumps(payload, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
