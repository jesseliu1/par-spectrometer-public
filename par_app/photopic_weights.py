def build_photopic_curve(wavelengths: np.ndarray) -> np.ndarray:
    """返回 V(λ)；仅在 CIE 360–830 nm 范围内作分段线性插值。"""
    values = np.asarray(wavelengths, dtype=float)
    return np.interp(values, _PHOTOPIC_NODES[:, 0], _PHOTOPIC_NODES[:, 1], left=0., right=0.)
